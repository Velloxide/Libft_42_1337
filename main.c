#include "libft.h"
#include <stdio.h>
#include <stdlib.h>

static const char	*g_cases[] = {
	"0",
	"42",
	"-42",
	"+42",
	"0042",
	"-0042",
	"2147483647",
	"-2147483648",
	"2147483648",
	"-2147483649",
	"4294967295",
	"4294967296",
	"-4294967296",
	"9223372036854775807",
	"9223372036854775808",
	"-9223372036854775808",
	"-9223372036854775809",
	"18446744073709551615",
	"18446744073709551616",
	"99999999999999999999",
	"-99999999999999999999",
	"00009223372036854775807",
	"00009223372036854775808",
	"-00009223372036854775808",
	"-00009223372036854775809",
	"000000000000000000000000042",
	"  \t\n\v\f\r42",
	"  -42  ",
	"\t\n  +7",
	"42abc",
	"2147483647abc",
	"abc",
	"",
	"   ",
	"+",
	"-",
	"+-5",
	"-+5",
	"--5",
	"++5",
	"- 5",
	"1 2",
	NULL
};

int	main(void)
{
	int	i;
	int	expected;
	int	got;
	int	fails;

	i = 0;
	fails = 0;
	while (g_cases[i])
	{
		expected = atoi(g_cases[i]);
		got = ft_atoi(g_cases[i]);
		if (expected != got)
		{
			printf("FAIL  \"%s\"  atoi=%d  ft_atoi=%d\n", g_cases[i], expected,
				got);
			fails++;
		}
		else
			printf("OK    \"%s\"  -> %d\n", g_cases[i], got);
		i++;
	}
	printf("\n%d test(s), %d fail(s)\n", i, fails);
	return (fails != 0);
}
