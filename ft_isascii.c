int	ft_isascii(int c)
{
	return (!(c & ~0x7F));
}
//   0000 0000 | 0000 0000 | 0000 0001 | 0000 0001 = 257
// & 1111 1111 | 1111 1111 | 1111 1111 | 1000 0000 = ~127
//-------------------------------------------------------
//   0000 0000 | 0000 0000 | 0000 0001 | 0000 0000 = 256 != 127
